import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const infoPath = path.join(root, "public", "images", "info.json");
const sourceDir = path.join(root, "images");
const outDir = path.join(root, "public", "_media", "albums");
const postsOutDir = path.join(root, "public", "_media", "posts");
const generatedDir = path.join(root, "src", "generated");
const manifestPath = path.join(generatedDir, "media-manifest.json");
const bannerManifestPath = path.join(generatedDir, "banner-manifest.ts");
const widths = [360, 720];
const imageExt = /\.(?:avif|jpe?g|png|gif|webp)$/i;

function fileHash(file) {
	return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex").slice(0, 20);
}

function sourceKey(album, file) {
	return `${album}/${file}`.replaceAll("\\", "/");
}

function sourceUrl(entry, file) {
	const dirs = Array.isArray(entry.photo_dir_urls) ? entry.photo_dir_urls : [];
	const dir = dirs.find((url) => typeof url === "string" && /^https?:\/\//.test(url));
	if (!dir) return null;
	return `${dir.replace(/\/+$/, "")}/${encodeURIComponent(file)}`;
}

function readManifest() {
	try {
		return JSON.parse(fs.readFileSync(manifestPath, "utf8"));
	} catch {
		return null;
	}
}

async function buildAlbum(entry, albums, previous) {
	const album = String(entry.title || "").trim();
	if (!album) return;
	const folder = path.join(sourceDir, album);
	if (!fs.existsSync(folder)) return;
	const previousItems = new Map(
		(previous?.albums?.[album] ?? []).map((item) => [item.sourceKey, item]),
	);
	const files = fs
		.readdirSync(folder, { withFileTypes: true })
		.filter((item) => item.isFile() && imageExt.test(item.name))
		.map((item) => item.name)
		.sort((a, b) => a.localeCompare(b, "zh-CN"));
	const records = [];
	for (const file of files) {
		const sourcePath = path.join(folder, file);
		const hash = fileHash(sourcePath);
		const key = sourceKey(album, file);
		const previousItem = previousItems.get(key);
		const outputs = [];
		for (const width of widths) {
			const outputName = `${hash}-${width}.webp`;
			const outputPath = path.join(outDir, outputName);
			const outputUrl = `/_media/albums/${outputName}`;
			const cached =
				previousItem?.webp?.find((item) => item.width === width && item.url === outputUrl) &&
				fs.existsSync(outputPath);
			if (!cached) {
				fs.mkdirSync(outDir, { recursive: true });
				await sharp(sourcePath)
					.rotate()
					.resize({ width, withoutEnlargement: true, fit: "inside" })
					.webp({ quality: width <= 360 ? 74 : 80, effort: 4 })
					.toFile(outputPath);
			}
			outputs.push({ width, url: outputUrl });
		}
		const metadata = await sharp(sourcePath).metadata();
		records.push({
			id: key,
			kind: "image",
			sourceKey: key,
			fileName: file,
			originalUrl: sourceUrl(entry, file),
			width: metadata.width ?? previousItem?.width ?? 0,
			height: metadata.height ?? previousItem?.height ?? 0,
			aspectRatio:
				metadata.width && metadata.height
					? Number((metadata.width / metadata.height).toFixed(5))
					: previousItem?.aspectRatio ?? 1.5,
			webp: outputs,
			thumbnail: outputs[0]?.url ?? "",
			medium: outputs.at(-1)?.url ?? outputs[0]?.url ?? "",
			hash,
			cacheVersion: hash.slice(0, 12),
			placeholder: { type: "color", value: "#d9dee5" },
		});
	}
	albums[album] = records;
}

function walkImages(directory, out = []) {
	if (!fs.existsSync(directory)) return out;
	for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
		const full = path.join(directory, entry.name);
		if (entry.isDirectory()) walkImages(full, out);
		else if (entry.isFile() && imageExt.test(entry.name)) out.push(full);
	}
	return out;
}

function writeBannerManifest() {
	const configSource = fs.readFileSync(path.join(root, "src", "config.ts"), "utf8");
	const bannerDir =
		/albumsInfoDir:\s*"([^"]+)"/.exec(configSource)?.[1] ?? "public/images";
	const publicDir = path.join(root, "public");
	const sourceDir = path.join(root, bannerDir);
	const listImages = (folder) =>
		walkImages(path.join(sourceDir, folder))
			.map((file) =>
				`/${path
					.relative(publicDir, file)
					.split(path.sep)
					.map(encodeURIComponent)
					.join("/")}`,
			)
			.sort((a, b) => a.localeCompare(b, "zh-CN"));

	const manifest = {
		schema: 1,
		generator: "scripts/build-media.mjs",
		sourceDir: bannerDir.replaceAll("\\", "/"),
		fullBanner: listImages("fullBanner"),
		wideBanner: listImages("wideBanner"),
	};
	const body = [
		"// Generated by scripts/build-media.mjs. Do not edit manually.",
		`export const bannerManifest = ${JSON.stringify(manifest, null, "\t")} as const;`,
		"",
	].join("\n");
	fs.mkdirSync(generatedDir, { recursive: true });
	const current = fs.existsSync(bannerManifestPath)
		? fs.readFileSync(bannerManifestPath, "utf8")
		: "";
	if (current !== body) fs.writeFileSync(bannerManifestPath, body);
}

async function buildPostMedia(previous) {
	const sourceRoot = path.join(root, "public", "data", "posts");
	const previousPosts = previous?.posts ?? {};
	const records = {};
	for (const sourcePath of walkImages(sourceRoot)) {
		const relative = path.relative(path.join(root, "public"), sourcePath).split(path.sep).join("/");
		const sourceUrl = `/${relative}`;
		const hash = fileHash(sourcePath);
		const outputName = `${hash}-720.webp`;
		const outputPath = path.join(postsOutDir, outputName);
		const outputUrl = `/_media/posts/${outputName}`;
		const cached =
			previousPosts[sourceUrl]?.medium === outputUrl && fs.existsSync(outputPath);
		if (!cached) {
			fs.mkdirSync(postsOutDir, { recursive: true });
			await sharp(sourcePath)
				.rotate()
				.resize({ width: 720, withoutEnlargement: true, fit: "inside" })
				.webp({ quality: 80, effort: 4 })
				.toFile(outputPath);
		}
		const metadata = await sharp(sourcePath).metadata();
		records[sourceUrl] = {
			id: sourceUrl,
			kind: "image",
			sourceUrl,
			originalUrl: sourceUrl,
			width: metadata.width ?? 0,
			height: metadata.height ?? 0,
			webp: [{ width: Math.min(720, metadata.width ?? 720), url: outputUrl }],
			thumbnail: outputUrl,
			medium: outputUrl,
			hash,
			cacheVersion: hash.slice(0, 12),
			placeholder: { type: "color", value: "#d9dee5" },
		};
	}
	return records;
}

const entries = JSON.parse(fs.readFileSync(infoPath, "utf8"));
if (!Array.isArray(entries)) {
	throw new Error("public/images/info.json must contain an array");
}
const previous = readManifest();
const albums = {};
for (const entry of entries) {
	if (entry && typeof entry === "object" && entry.hidden !== true) {
		await buildAlbum(entry, albums, previous);
	}
}
const posts = await buildPostMedia(previous);

const manifest = {
	schema: 1,
	generator: "scripts/build-media.mjs",
	widths,
	albums,
	posts,
};

fs.mkdirSync(generatedDir, { recursive: true });
const body = `${JSON.stringify(manifest, null, 2)}\n`;
const current = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, "utf8") : "";
if (current !== body) fs.writeFileSync(manifestPath, body);
writeBannerManifest();

const count = Object.values(albums).reduce((sum, items) => sum + items.length, 0);
console.log(
	`[media] ${count} album photos and ${Object.keys(posts).length} article images`,
);
